test('YouTube links route to both browser converters and import a downloaded file', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  // Verify our handoff without depending on the external converters being available.
  await context.route('https://flvto.world/**', route => route.fulfill({ body: 'Flvto test destination', contentType: 'text/html' }));
  await context.route('https://ytmp3.gl/**', route => route.fulfill({ body: 'YTMP3 test destination', contentType: 'text/html' }));
  await page.goto('/');
  await page.getByRole('button', { name: 'Add music', exact: true }).click();
  await page.getByRole('tab', { name: 'Paste links' }).click();
  await page.getByRole('textbox', { name: 'Direct audio links' }).fill('https://youtu.be/qV-3UMfcWBc?si=tracking');
  await expect(page.getByRole('tab', { name: 'YouTube', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.getByRole('button', { name: 'Copy video link', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Link copied — ready to paste' })).toBeVisible();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('https://www.youtube.com/watch?v=qV-3UMfcWBc');
  for (const [name, url] of [['Open Flvto', 'https://flvto.world/'], ['Open YTMP3 fallback', 'https://ytmp3.gl/']]) {
    const popup = page.waitForEvent('popup');
    await page.getByRole('button', { name, exact: true }).click();
    const converter = await popup;
    await expect(converter).toHaveURL(url);
    await converter.close();
  }
  await expect(page.getByText(/After downloading from YTMP3/)).toBeVisible();
  const picker = page.waitForEvent('filechooser');
  await page.getByRole('button', { name: 'Import downloaded MP3' }).click();
  await (await picker).setFiles({ name: 'Downloaded.wav', mimeType: 'audio/wav', buffer: wave() });
  await expect(page.getByRole('button', { name: 'Play Downloaded by Unknown artist' })).toBeVisible();
});
